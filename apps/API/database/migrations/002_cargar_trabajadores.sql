INSERT INTO cat_cargo (codigo, nombre, id_estado)
SELECT
  UPPER(REPLACE(REPLACE(REPLACE(LEFT(nombre, 30), ' ', '_'), '-', '_'), ',', '')),
  nombre,
  estado.id
FROM cargos CROSS JOIN estado
ON CONFLICT (codigo) DO UPDATE SET nombre = EXCLUDED.nombre;

