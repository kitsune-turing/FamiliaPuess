-- 2. Asegurar que exista la sede
WITH estado AS (
  SELECT id FROM cat_estado WHERE codigo = 'ACTIVO'
)
INSERT INTO sede (nombre, direccion, id_estado)
SELECT 'Sede Principal', 'Direccion pendiente de configurar', id FROM estado
ON CONFLICT (nombre) DO NOTHING;

